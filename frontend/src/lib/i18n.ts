export type MessageKey = keyof typeof english
export type MessageValues = Record<string, string | number>
export const isLanguage = (value: unknown): value is Language => value === "es" || value === "en"
export function text(language: Language, source: MessageKey | "", values: MessageValues = {}): string {
  const translated = language === "en" && source ? english[source] : source
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
}

/** Translate stored client errors at display time, without changing protocol or
 * retry identity. Unknown errors retain their original, React-escaped text. */
export function errorText(language: Language, source: string): string {
  if (language === "es") return source
  if (Object.hasOwn(english, source)) return english[source as MessageKey]
  const suffix = " La solicitud original sigue sin confirmar."
  if (source.endsWith(suffix)) return `${errorText(language, source.slice(0, -suffix.length))} ${text(language, "La solicitud original sigue sin confirmar.")}`
  const limited = /^Demasiados intentos\. Espera (\d+) segundos antes de (crear otra cuenta|volver a entrar)\.$/.exec(source)
  if (limited) return text(language, "Demasiados intentos. Espera {seconds} segundos antes de {action}.", { seconds: limited[1], action: text(language, limited[2] as "crear otra cuenta" | "volver a entrar") })
  return source
}
