const clock = () => new Date("2026-10-03T12:00:00Z")

function clientFixture(two = false) {
  const marks = new Set(["2026-09-30", "2026-10-01"])
  const second = { ...front, id: "00000000-0000-4000-8000-000000000002", name: "Lectura" }
  const project = (q: DashboardQuery): DashboardPage => {
    const dates = [...marks].filter(day => day >= q.start && day <= q.end).sort()
    return { start: q.start, end: q.end, offset: q.offset ?? 0, limit: 20, total: two ? 2 : 1,
      items: [{ front, marked_dates: dates, count: dates.length, last_registered_day: [...marks].sort().at(-1) ?? null },
        ...(two ? [{ front: second, marked_dates: [], count: 0, last_registered_day: null }] : [])] }
  }
  const client: ActivityApi = {
    supportsFrontIcons: true,
    dashboard: vi.fn(async q => project(q)),
    createFront: vi.fn(async () => front), patchFront: vi.fn(async () => front),
    writeCheck: vi.fn(async (id, day, marked) => {
      if (marked) marks.add(day); else marks.delete(day)
      return { front_id: id, day, marked }
    }),
    confirmedDashboard: vi.fn((_id, q) => project(q)),
  }
  return { client, marks, project }
}

function onboardingFixture(dismissed = false) {
  const { client, project } = clientFixture()
  const projected = (q: DashboardQuery) => ({ ...project(q), onboarding: { version: 1 as const, tutorialDismissed: dismissed } })
  vi.mocked(client.dashboard).mockImplementation(async q => projected(q))
  vi.mocked(client.confirmedDashboard!).mockImplementation((_id, q) => projected(q))
  client.dismissTutorial = vi.fn(async () => { dismissed = true })
  return { client }
}

